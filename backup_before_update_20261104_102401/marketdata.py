"""REAL historical gold / silver prices (no API key needed).

Primary source : Yahoo Finance chart API (COMEX futures, monthly bars)
Backup source  : Stooq monthly CSV (spot XAU/XAG in USD)

Nothing here is ever generated by an AI model. If no source answers, DataUnavailable is raised and the chat
tells the user honestly instead of guessing numbers. Future years are never invented or forecast.
"""
import csv
import io
import re
import threading
import time
from datetime import date, datetime, timezone

import requests

ASSETS = {
    "gold": {"label": "Gold", "yahoo": "GC=F", "stooq": "xauusd", "yahoo_name": "COMEX gold futures (GC=F)",
             "stooq_name": "spot gold XAU/USD"},
    "silver": {"label": "Silver", "yahoo": "SI=F", "stooq": "xagusd", "yahoo_name": "COMEX silver futures (SI=F)",
               "stooq_name": "spot silver XAG/USD"},
}
UNIT = "USD per troy ounce"
CACHE_SECONDS = 3600
_CACHE = {}
_LOCK = threading.Lock()
_HEADERS = {"User-Agent": "Mozilla/5.0 (compatible; UpianAI/1.0)"}


class DataUnavailable(Exception):
    pass


# ----------------------------------------------------------------------------- fetching
def _get(url, params=None):
    try:
        resp = requests.get(url, params=params, headers=_HEADERS, timeout=(5, 15))
    except requests.RequestException as exc:
        raise DataUnavailable("network error: %s" % str(exc)[:120])
    if resp.status_code >= 400:
        raise DataUnavailable("HTTP %s from %s" % (resp.status_code, url.split("/")[2]))
    return resp


def parse_yahoo(payload):
    """Yahoo chart JSON -> (bars, latest). bars = [{date, open, high, low, close}] oldest first."""
    try:
        result = payload["chart"]["result"][0]
        stamps = result["timestamp"]
        q = result["indicators"]["quote"][0]
    except (KeyError, IndexError, TypeError):
        raise DataUnavailable("unexpected Yahoo response")
    by_date = {}
    for i, ts in enumerate(stamps):
        close = (q.get("close") or [None] * len(stamps))[i]
        if close is None:
            continue

        def pick(key):
            v = (q.get(key) or [None] * len(stamps))[i]
            return float(close if v is None else v)

        d = datetime.fromtimestamp(ts, tz=timezone.utc).date()
        by_date[d] = {"date": d, "open": pick("open"), "high": pick("high"), "low": pick("low"), "close": float(close)}
    bars = [by_date[d] for d in sorted(by_date)]
    meta = result.get("meta") or {}
    latest = None
    if meta.get("regularMarketPrice") and meta.get("regularMarketTime"):
        latest = (datetime.fromtimestamp(meta["regularMarketTime"], tz=timezone.utc).date(), float(meta["regularMarketPrice"]))
    elif bars:
        latest = (bars[-1]["date"], bars[-1]["close"])
    return bars, latest


def parse_stooq(text):
    rows = list(csv.DictReader(io.StringIO(text.strip())))
    bars = []
    for r in rows:
        try:
            d = datetime.strptime(r["Date"], "%Y-%m-%d").date()
            close = float(r["Close"])
            bars.append({"date": d, "open": float(r.get("Open") or close), "high": float(r.get("High") or close),
                         "low": float(r.get("Low") or close), "close": close})
        except (KeyError, ValueError, TypeError):
            continue
    if not bars:
        raise DataUnavailable("unexpected Stooq response")
    bars.sort(key=lambda b: b["date"])
    return bars, (bars[-1]["date"], bars[-1]["close"])


def _from_yahoo(asset, start_year):
    p1 = int(datetime(start_year, 1, 1, tzinfo=timezone.utc).timestamp())
    p2 = int(time.time()) + 86400
    url = "https://query1.finance.yahoo.com/v8/finance/chart/" + ASSETS[asset]["yahoo"]
    data = _get(url, {"period1": p1, "period2": p2, "interval": "1mo"}).json()
    bars, latest = parse_yahoo(data)
    return bars, latest, ASSETS[asset]["yahoo_name"] + ", Yahoo Finance"


def _from_stooq(asset, start_year):
    params = {"s": ASSETS[asset]["stooq"], "i": "m", "d1": "%d0101" % start_year,
              "d2": date.today().strftime("%Y%m%d")}
    bars, latest = parse_stooq(_get("https://stooq.com/q/d/l/", params).text)
    return bars, latest, ASSETS[asset]["stooq_name"] + ", Stooq"


def get_history(asset, start_year):
    """Return (bars, latest, source). Cached for an hour."""
    key = (asset, start_year)
    with _LOCK:
        hit = _CACHE.get(key)
        if hit and time.time() - hit[0] < CACHE_SECONDS:
            return hit[1]
    errors = []
    for fn in (_from_yahoo, _from_stooq):
        try:
            result = fn(asset, start_year)
            if result[0]:
                with _LOCK:
                    _CACHE[key] = (time.time(), result)
                return result
        except DataUnavailable as exc:
            errors.append(str(exc))
    raise DataUnavailable("; ".join(errors) or "no data")


# ----------------------------------------------------------------------------- understanding the question
_ASSET = re.compile(r"\b(gold|silver)\b", re.I)
_PRICE = re.compile(r"\b(price|prices|rate|rates|cost|value|worth|history)\b", re.I)
_NOT_DATA = re.compile(r"\b(why|how (?:do|does|is|are|can)|explain|reason|affect\w*|determin\w*|predict\w*|forecast\w*)\b", re.I)


def detect_asset(prompt):
    """'gold' / 'silver' when the prompt asks for its price, otherwise None."""
    if _NOT_DATA.search(prompt) or not _PRICE.search(prompt):
        return None
    m = _ASSET.search(prompt)
    return m.group(1).lower() if m else None


def detect_range(prompt, today=None):
    """-> (start_year, end_year) or None when the user asked for the current price."""
    today = today or date.today()
    years = [int(y) for y in re.findall(r"\b(19[5-9]\d|20\d\d)\b", prompt)]
    if years:
        return min(years), max(years)
    m = re.search(r"\b(?:last|past|previous)\s+(\d{1,2})\s*(?:years?|yrs?)\b", prompt, re.I)
    if m:
        n = max(1, int(m.group(1)))
        return today.year - n + 1, today.year
    if re.search(r"\b(?:last|past)\s+decade\b", prompt, re.I):
        return today.year - 9, today.year
    return None


# ----------------------------------------------------------------------------- building the answer
def _money(v):
    return "${:,.2f}".format(v)


def _ranges(years):
    years, out = sorted(years), []
    for y in years:
        if out and y == out[-1][1] + 1:
            out[-1][1] = y
        else:
            out.append([y, y])
    return ", ".join(str(a) if a == b else "%d–%d" % (a, b) for a, b in out)


def yearly_rows(bars, y0, y1):
    """Aggregate monthly bars into one row per year (Open, High, Low, Close, % change vs previous year-end)."""
    by_year = {}
    for b in bars:
        by_year.setdefault(b["date"].year, []).append(b)
    rows, prev_close = {}, None
    for y in sorted(by_year):
        bs = sorted(by_year[y], key=lambda b: b["date"])
        close = bs[-1]["close"]
        rows[y] = {"year": y, "open": bs[0]["open"], "high": max(b["high"] for b in bs),
                   "low": min(b["low"] for b in bs), "close": close,
                   "change": (close / prev_close - 1) * 100 if prev_close else None}
        prev_close = close
    return {y: r for y, r in rows.items() if y0 <= y <= y1}


def report(asset, prompt, today=None):
    """Return {'markdown', 'slug', 'source'}. Raises DataUnavailable when no real data can be fetched."""
    today = today or date.today()
    label = ASSETS[asset]["label"]
    rng = detect_range(prompt, today)
    if rng is None:
        bars, latest, source = get_history(asset, today.year - 1)
        d, price = latest
        md = ("### %s price now (%s)\n\n| Date | Price (USD per troy ounce) |\n|---|---|\n| %s | %s |\n\n"
              "**Notes**\n- Source: %s. Futures prices differ slightly from spot.\n"
              % (label, UNIT, d.isoformat(), _money(price), source))
        return {"markdown": md, "slug": "%s-price-latest" % asset, "source": source[:80]}

    y0, y1 = rng
    if y1 - y0 > 60:
        y0 = y1 - 60
    last_year = min(y1, today.year)
    if y0 > today.year:
        raise DataUnavailable("%d is in the future, so there is no real %s price to show." % (y0, asset))
    bars, latest, source = get_history(asset, max(y0 - 1, 1950))
    rows = yearly_rows(bars, y0, last_year)
    if not rows:
        raise DataUnavailable("no %s price data was found for %d–%d." % (asset, y0, last_year))

    shown = sorted(rows)
    title_end = shown[-1]
    head = "### %s price by year, %d–%d (%s)" % (label, shown[0], title_end, UNIT)
    lines = [head, "", "| Year | Open (USD) | High (USD) | Low (USD) | Close (USD) | Change vs prev. year |",
             "|---|---|---|---|---|---|"]
    for y in shown:
        r = rows[y]
        ch = "n/a" if r["change"] is None else "%+.1f%%" % r["change"]
        lines.append("| %d | %s | %s | %s | %s | %s |" % (
            y, _money(r["open"]), _money(r["high"]), _money(r["low"]),
            _money(r["close"]), ch))

    notes = ["Source: %s, monthly data in %s. Close = last price of the year. High/Low = highest/lowest of the year."
             % (source, UNIT)]
    if today.year in rows and latest:
        notes.append("%d is year-to-date: its Close is the latest price available (%s)." % (today.year, latest[0].isoformat()))
    missing = [y for y in range(y0, last_year + 1) if y not in rows]
    if missing:
        notes.append("No data was available from the source for: %s." % _ranges(missing))
    if y1 > today.year:
        notes.append("%s are in the future, so no real price exists for them yet. They are left out on purpose; "
                     "no forecast or made-up numbers are shown." % _ranges(range(max(y0, today.year + 1), y1 + 1)))
    lines += ["", "**Notes**"] + ["- " + n for n in notes]
    return {"markdown": "\n".join(lines), "slug": "%s-price-%d-%d" % (asset, shown[0], title_end), "source": source[:80]}
